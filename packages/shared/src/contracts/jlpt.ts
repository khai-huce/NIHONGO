/** Catalog and account study. Answer keys are excluded from public catalog views. */
export interface JlptQuestion { id: string; prompt: string; passage: string; options: string[]; correctIndex: number; explanation: string }
export type JlptLevel = 'N5' | 'N4' | 'N3' | 'N2' | 'N1';
export type JlptResourceKind = 'kanji' | 'vocabulary' | 'grammar' | 'reading' | 'shadowing' | 'kana';
export interface JlptResourceInput { id: string; kind: JlptResourceKind; targetId: string }
export interface JlptSessionInput {
  id: string; title: string; description: string; estimatedMinutes: number;
  resources: JlptResourceInput[];
  questions?: JlptQuestion[];
}
export interface JlptDraft {
  title: string; description: string; sourceId: string | null; sessions: JlptSessionInput[];
  passPercent?: number;
}
export interface JlptResourceView extends JlptResourceInput {
  available: boolean; title: string; subtitle: string; level: string | null;
  /** A learner route generated by the server, never an authored URL. Null when target is unavailable. */
  href: string | null;
}
export interface JlptSessionView extends Omit<JlptSessionInput, 'resources' | 'questions'> { resources: JlptResourceView[]; questionCount: number }
export interface JlptCounts { sessionCount: number; resourceCount: number; kanjiCount: number; estimatedMinutes: number }
export interface JlptRoadmapSummary extends JlptCounts {
  id: string; level: JlptLevel; title: string; description: string; publishedVersion: number;
  resourceKinds: JlptResourceKind[];
  passPercent: number;
}
export interface JlptRoadmapView extends JlptRoadmapSummary {
  source: { id: string; name: string; url: string; license: string; licenseUrl: string; attribution: string };
  sessions: JlptSessionView[];
}
export interface AdminJlptRoadmap {
  id: string; level: JlptLevel; version: number; publishedVersion: number | null;
  archivedAt: string | null; draft: JlptDraft;
}
export interface JlptPreview extends JlptCounts {
  draft: JlptDraft; sessions: JlptSessionView[];
  /** False until every session has an available resource and a real source is selected. */
  canPublish: boolean; issues: string[];
}
export interface JlptResourceOption extends Omit<JlptResourceView, 'id'> {}
export interface JlptResourceSearch { items: JlptResourceOption[]; page: number; pageSize: number; total: number }

export interface JlptStudySession { id: string; unlocked: boolean; completedAt: string | null; bestScore: number | null; attempts: number; activeAttemptId: string | null; latestAttemptId: string | null }
export interface JlptStudy { userId: string; roadmapId: string; lastSessionId: string | null; resumeSessionId: string | null; completedCount: number; percent: number; kanjiLearned: number; streak: number; sessions: JlptStudySession[] }
export interface JlptAttemptView {
  id: string; sessionId: string; sessionTitle: string; level: JlptLevel; publishedVersion: number; version: number;
  passPercent: number; questions: Array<Omit<JlptQuestion, 'correctIndex' | 'explanation'> & { correctIndex?: number; explanation?: string }>;
  answers: Record<string, number>; startedAt: string; submittedAt: string | null; correctCount: number | null; score: number | null; passed: boolean | null;
}
